"""
backend/models.py
-----------------
SQLAlchemy ORM models for ClipGenerator.

Models:
  - Job   : Tracks a video processing job (upload -> transcribe -> analyze -> clip -> done)
  - Clip  : Represents a single extracted clip (landscape + portrait) belonging to a Job
"""

from __future__ import annotations

import enum
from datetime import datetime
from typing import List, Optional

from sqlalchemy import (
    DateTime,
    Float,
    ForeignKey,
    String,
    Text,
    func,
)
from sqlalchemy.orm import Mapped, mapped_column, relationship

from backend.database import Base


class JobStatus(str, enum.Enum):
    """Life-cycle states of a processing Job."""
    queued       = "queued"
    transcribing = "transcribing"
    analyzing    = "analyzing"
    clipping     = "clipping"
    done         = "done"
    error        = "error"


class Job(Base):
    """Represents a single video upload and its end-to-end processing lifecycle."""
    __tablename__ = "jobs"
    __allow_unmapped__ = True

    id: Mapped[str] = mapped_column(
        String(64),
        primary_key=True,
        index=True,
        doc="Unique UUID job identifier.",
    )

    filename: Mapped[str] = mapped_column(
        String(512),
        nullable=False,
        doc="Original filename of the uploaded video.",
    )

    video_path: Mapped[Optional[str]] = mapped_column(
        String(1024),
        nullable=True,
        default=None,
        doc="Path to the uploaded video file on disk.",
    )

    status: Mapped[str] = mapped_column(
        String(32),
        nullable=False,
        default=JobStatus.queued.value,
        index=True,
        doc="Current pipeline status of this job.",
    )

    error: Mapped[Optional[str]] = mapped_column(
        Text,
        nullable=True,
        default=None,
        doc="Error message if processing failed.",
    )

    created_at: Mapped[datetime] = mapped_column(
        DateTime,
        nullable=False,
        default=datetime.utcnow,
        server_default=func.now(),
        doc="UTC timestamp when the job was created.",
    )

    updated_at: Mapped[datetime] = mapped_column(
        DateTime,
        nullable=False,
        default=datetime.utcnow,
        onupdate=datetime.utcnow,
        server_default=func.now(),
        doc="UTC timestamp when the job was last updated.",
    )

    clips: Mapped[List[Clip]] = relationship(
        "Clip",
        back_populates="job",
        cascade="all, delete-orphan",
        lazy="selectin",
        order_by="Clip.start_sec",
    )

    def __repr__(self) -> str:
        return f"<Job id={self.id!r} filename={self.filename!r} status={self.status!r}>"


class Clip(Base):
    """Represents an AI-selected clip extracted from a Job."""
    __tablename__ = "clips"
    __allow_unmapped__ = True

    id: Mapped[str] = mapped_column(
        String(64),
        primary_key=True,
        index=True,
        doc="Unique UUID clip identifier.",
    )

    job_id: Mapped[str] = mapped_column(
        String(64),
        ForeignKey("jobs.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
        doc="Foreign key to the parent Job.",
    )

    title: Mapped[str] = mapped_column(
        String(512),
        nullable=False,
        default="",
        doc="Short title generated by the AI.",
    )

    reason: Mapped[str] = mapped_column(
        Text,
        nullable=False,
        default="",
        doc="Explanation of why this segment was selected.",
    )

    start_sec: Mapped[float] = mapped_column(
        Float,
        nullable=False,
        doc="Clip start time in seconds.",
    )

    end_sec: Mapped[float] = mapped_column(
        Float,
        nullable=False,
        doc="Clip end time in seconds.",
    )

    landscape_path: Mapped[Optional[str]] = mapped_column(
        String(1024),
        nullable=True,
        default=None,
        doc="Relative path to 16:9 landscape video.",
    )

    portrait_path: Mapped[Optional[str]] = mapped_column(
        String(1024),
        nullable=True,
        default=None,
        doc="Relative path to 9:16 portrait video.",
    )

    created_at: Mapped[datetime] = mapped_column(
        DateTime,
        nullable=False,
        default=datetime.utcnow,
        server_default=func.now(),
        doc="UTC timestamp when the clip was generated.",
    )

    job: Mapped[Job] = relationship(
        "Job",
        back_populates="clips",
    )

    def __repr__(self) -> str:
        return f"<Clip id={self.id!r} job_id={self.job_id!r} title={self.title!r}>"
